# 生成 `code/shared/font-charset.mjs`：年度总结卡片子集字体要覆盖的字符集。
#
# 口径（总监 2026-11-14 定）：中文取 **GB2312 全部 6763 字**（不是只取 3500 常用字），
# 另加 GB2312 的符号区、拉丁字母、数字与常用标点。emoji 不在这里（取自
# `code/web/src/js/tag-emoji.js` 的 424 个，子集脚本自己读）。
#
# 用法：python code/scripts/gen-font-charset.py
# 产物：code/shared/font-charset.mjs（已提交，子集脚本与缺字检查都读它）
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'shared', 'font-charset.mjs')


def gb2312_chars():
    seen = []
    for a in range(0xA1, 0xF8):
        for b in range(0xA1, 0xFF):
            try:
                ch = bytes([a, b]).decode('gb2312')
            except Exception:
                continue
            if ch not in seen:
                seen.append(ch)
    return seen


def is_hanzi(ch):
    return '\u4e00' <= ch <= '\u9fff'


def esc(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch == '\\':
            out.append('\\\\')
        elif ch == "'":
            out.append("\\'")
        elif 0x20 <= code <= 0x7E:
            out.append(ch)
        else:
            out.append('\\u%04x' % code)
    return ''.join(out)


chars = gb2312_chars()
hanzi = ''.join(c for c in chars if is_hanzi(c))
symbols = ''.join(c for c in chars if not is_hanzi(c))
latin = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
# ASCII 可见字符（space .. ~）：数字、百分比、等号、连字符、点号等都会出现在卡片上，
# 少一个就等于缺字（2026-11-14 实测：只收拉丁数字时卡片触发「缺字」兜底）。
ascii_punct = ''.join(chr(c) for c in range(0x20, 0x7F) if not chr(c).isalnum())
# 卡片实际用到的、GB2312 之外的中文标点与符号（渲染文案里有）。
extra = '…—～·“”‘’％×（）《》、，。：；！？'


with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// AUTO-GENERATED by code/scripts/gen-font-charset.py — 不要手改。\n')
    f.write('// 口径：GB2312 全部 6763 汉字 + 其符号区 + 拉丁/数字 + 常用标点；emoji 见 tag-emoji.js。\n')
    f.write("export const GB2312_HANZI = '%s';\n" % esc(hanzi))
    f.write("export const GB2312_SYMBOLS = '%s';\n" % esc(symbols))
    f.write("export const LATIN_DIGITS = '%s';\n" % esc(latin))
    f.write("export const ASCII_PUNCT = '%s';\n" % esc(ascii_punct))
    f.write("export const EXTRA_PUNCT = '%s';\n" % esc(extra))
    f.write("export const FONT_CHARSET = GB2312_HANZI + GB2312_SYMBOLS + LATIN_DIGITS + ASCII_PUNCT + EXTRA_PUNCT;\n")
    f.write('export const HANZI_COUNT = %d;\n' % len(hanzi))

print('hanzi', len(hanzi), 'symbols', len(symbols), 'ascii', len(ascii_punct), 'extra', len(extra))
